const classMultiplier = {
  Sleeper: 1,
  ChairCar: 1.2,
  "3A": 1.45,
  "2A": 1.75,
  "1A": 2.2,
};

const normalizeStation = (value) =>
  String(value || "")
    .replace(/\(.*?\)/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .trim();

const getIndianTrainsForRoute = ({ from, to, travelClass }) => {
  const fromNorm = normalizeStation(from);
  const toNorm = normalizeStation(to);

  const list = TRAIN_CATALOG.filter(
    (t) => normalizeStation(t.from).includes(fromNorm) && normalizeStation(t.to).includes(toNorm)
  ).slice(0, 12);

  return list.map((train) => {
    const baseFare = Math.max(300, Math.floor(train.durationMin * 2.8));
    const fare = Math.round(baseFare * (classMultiplier[travelClass] || 1));
    return {
      trainId: train.number,
      trainNumber: train.number,
      trainName: train.name,
      from: train.from,
      to: train.to,
      durationMinutes: train.durationMin,
      route: train.route,
      baseFare,
      fare,
      travelClass,
      source: "Indian Rail Data",
      live: false,
    };
  });
};

const getTrainByNumber = (number) => TRAIN_CATALOG.find((t) => t.number === String(number || ""));

